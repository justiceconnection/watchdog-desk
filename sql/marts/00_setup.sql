-- 00_setup.sql: seeds, snapshot metadata and shared helper tables.
--
-- Run by sql/build_marts.py (or the DuckDB CLI, see docs/data-contract.md) on an
-- IN-MEMORY connection with data/fedspend.duckdb attached READ_ONLY and on the
-- search path. Every statement is parameterised by the session variable
--   SET VARIABLE agency = '<3-digit toptier code>';
-- Nothing here names a specific agency. Paths are relative to the repo root.
-- Tables whose names start with "_" are helpers and are never exported.

-- ---------------------------------------------------------------- seeds
CREATE OR REPLACE TABLE _seed_component_map AS
SELECT agency_code, federal_account_symbol, component_group, component, notes
FROM read_csv('sql/seeds/component_map.csv', header = true, all_varchar = true);

CREATE OR REPLACE TABLE _seed_sign_flips AS
SELECT agency_code, CAST(fiscal_year AS INTEGER) AS fiscal_year, treasury_account_symbol,
       measure, verified_by, CAST(verified_on AS DATE) AS verified_on, evidence
FROM read_csv('sql/seeds/file_b_sign_flips.csv', header = true, all_varchar = true);

CREATE OR REPLACE TABLE _seed_subaward_outliers AS
SELECT agency_code, subaward_sam_report_id, prime_award_unique_key,
       CAST(subaward_amount AS DOUBLE) AS subaward_amount, reason, source
FROM read_csv('sql/seeds/subaward_outliers.csv', header = true, all_varchar = true);

-- Sub-award outlier RULE: the single place the threshold lives (also read by
-- sql/checks/reconcile_marts.sql). One row; edit the CSV to change the rule.
CREATE OR REPLACE TABLE _seed_subaward_outlier_rule AS
SELECT rule_id, CAST(min_ratio_to_prime AS DOUBLE) AS min_ratio_to_prime,
       CAST(min_subaward_amount AS DOUBLE) AS min_subaward_amount,
       CAST(min_prime_award_amount_exclusive AS DOUBLE) AS min_prime_award_amount_exclusive,
       CAST(review_min_ratio_to_prime_exclusive AS DOUBLE) AS review_min_ratio_to_prime_exclusive,
       CAST(review_min_subaward_amount AS DOUBLE) AS review_min_subaward_amount, source
FROM read_csv('sql/seeds/subaward_outlier_rule.csv', header = true, all_varchar = true);

CREATE OR REPLACE TABLE _seed_award_component_rules AS
SELECT agency_code, CAST(rule_order AS INTEGER) AS rule_order, applies_to, match_column,
       match_type, upper(match_value) AS match_value, component,
       CAST(program_office_from_office AS BOOLEAN) AS program_office_from_office,
       nullif(null_office_program_office, '') AS null_office_program_office
FROM read_csv('sql/seeds/award_component_rules.csv', header = true, all_varchar = true);

-- metrics.md 6.2 rule 1 null-office step 2: assistance listing -> office (>= 95% share).
-- Generated by sql/seeds/listing_office_map.sql (python sql/build_marts.py --regen-listing-map).
CREATE OR REPLACE TABLE _seed_listing_office_map AS
SELECT agency_code, program_code, office
FROM read_csv('sql/seeds/listing_office_map.csv', header = true, all_varchar = true);

CREATE OR REPLACE TABLE _seed_state_codes AS
SELECT nullif(state_fips, '') AS state_fips, state_code, state_name
FROM read_csv('sql/seeds/state_codes.csv', header = true, all_varchar = true);

-- ---------------------------------------------------------------- snapshot metadata
-- data_as_of = fetched_at in data/raw/<agency>/reference/snapshot_info.json (UTC).
CREATE OR REPLACE TABLE _snapshot AS
SELECT agency.toptier_code                 AS agency_code,
       agency.agency_slug                  AS agency_slug,
       CAST(fetched_at AS TIMESTAMP)       AS data_as_of,
       CAST(CAST(fetched_at AS TIMESTAMP) AS DATE) AS data_as_of_date
FROM read_json_auto('data/raw/*/reference/snapshot_info.json');

CREATE OR REPLACE TABLE _params AS
SELECT getvariable('agency') AS agency_code,
       (SELECT data_as_of      FROM _snapshot WHERE agency_code = getvariable('agency')) AS data_as_of,
       (SELECT data_as_of_date FROM _snapshot WHERE agency_code = getvariable('agency')) AS data_as_of_date;

-- ---------------------------------------------------------------- federal account -> component
-- metrics.md 6.1. Agencies with a curated map: unmapped accounts become
-- 'Unmapped: <name>'. Agencies without a map: component = federal_account_name.
CREATE OR REPLACE TABLE _federal_accounts AS
WITH fa AS (
    SELECT federal_account_symbol, arg_max(federal_account_name, fiscal_year) AS federal_account_name
    FROM (SELECT federal_account_symbol, federal_account_name, fiscal_year
          FROM account_balances WHERE agency_code = getvariable('agency')
          UNION ALL
          SELECT federal_account_symbol, federal_account_name, fiscal_year
          FROM account_activity WHERE agency_code = getvariable('agency'))
    GROUP BY 1
), has_map AS (
    SELECT count(*) > 0 AS has_map FROM _seed_component_map WHERE agency_code = getvariable('agency')
)
SELECT fa.federal_account_symbol,
       fa.federal_account_name,
       CASE WHEN m.component IS NOT NULL THEN m.component_group
            WHEN (SELECT has_map FROM has_map) THEN 'Unmapped'
            ELSE fa.federal_account_name END                       AS component_group,
       CASE WHEN m.component IS NOT NULL THEN m.component
            WHEN (SELECT has_map FROM has_map) THEN 'Unmapped: ' || fa.federal_account_name
            ELSE fa.federal_account_name END                       AS component,
       m.component IS NOT NULL                                     AS component_mapped
FROM fa
LEFT JOIN _seed_component_map m
       ON m.agency_code = getvariable('agency') AND m.federal_account_symbol = fa.federal_account_symbol;

-- ---------------------------------------------------------------- latest period per FY
-- File A/B are FYTD snapshots: keep only the latest period per FY (metrics.md 1).
CREATE OR REPLACE TABLE _latest_period AS
SELECT fiscal_year,
       max(submission_period_num) AS latest_period,
       -- period P of FY y ends on the last day of fiscal month P (P1 = October of y-1)
       CAST(make_date(fiscal_year - 1, 10, 1) + to_months(max(submission_period_num)) - INTERVAL 1 DAY AS DATE)
                                  AS period_end_date
FROM account_balances
WHERE agency_code = getvariable('agency')
GROUP BY 1;

CREATE OR REPLACE TABLE _latest_period_b AS
SELECT fiscal_year, max(submission_period_num) AS latest_period
FROM account_activity
WHERE agency_code = getvariable('agency')
GROUP BY 1;

-- ---------------------------------------------------------------- File B lines, sign-corrected
-- One row per File B line at the latest period, with the per-measure sign
-- correction from the verified register (metrics.md 5.3, treatment (a)).
CREATE OR REPLACE TABLE _file_b_lines AS
SELECT b.fiscal_year,
       b.treasury_account_symbol,
       b.federal_account_symbol,
       b.program_activity_code,
       b.program_activity_name,
       b.program_activity_reporting_key,
       b.object_class_code,
       b.object_class_name,
       b.direct_or_reimbursable_funding_source,
       coalesce(b.obligations_incurred, 0)                   AS obligations_b,
       coalesce(b.gross_outlay_amount_FYB_to_period_end, 0)  AS outlays_b,
       fo.measure IS NOT NULL                                AS sign_corrected_obligations,
       fu.measure IS NOT NULL                                AS sign_corrected_outlays,
       CASE WHEN fo.measure IS NOT NULL THEN -1 ELSE 1 END * coalesce(b.obligations_incurred, 0)                  AS obligations_b_corr,
       CASE WHEN fu.measure IS NOT NULL THEN -1 ELSE 1 END * coalesce(b.gross_outlay_amount_FYB_to_period_end, 0) AS outlays_b_corr
FROM account_activity b
JOIN _latest_period_b lp
  ON lp.fiscal_year = b.fiscal_year AND lp.latest_period = b.submission_period_num
LEFT JOIN _seed_sign_flips fo
  ON fo.agency_code = b.agency_code AND fo.fiscal_year = b.fiscal_year
 AND fo.treasury_account_symbol = b.treasury_account_symbol AND fo.measure = 'obligations'
LEFT JOIN _seed_sign_flips fu
  ON fu.agency_code = b.agency_code AND fu.fiscal_year = b.fiscal_year
 AND fu.treasury_account_symbol = b.treasury_account_symbol AND fu.measure = 'outlays'
WHERE b.agency_code = getvariable('agency');

-- ---------------------------------------------------------------- award component rules
-- metrics.md 6.2. Normalised (upper-case) sub-agency name -> component.
CREATE OR REPLACE TABLE _sub_agency_rules AS
SELECT match_value AS sub_agency_name_uc, component, null_office_program_office
FROM _seed_award_component_rules
WHERE agency_code = getvariable('agency') AND match_column = 'sub_agency_name' AND match_type = 'exact';

-- Component for a NULL sub-agency (match_type 'null'); default 'Sub-agency not reported'.
CREATE OR REPLACE TABLE _null_sub_agency_rule AS
SELECT coalesce((SELECT min(component) FROM _seed_award_component_rules
                 WHERE agency_code = getvariable('agency') AND match_column = 'sub_agency_name'
                   AND match_type = 'null'), 'Sub-agency not reported') AS component;

CREATE OR REPLACE TABLE _listing_office AS
SELECT program_code, office FROM _seed_listing_office_map WHERE agency_code = getvariable('agency');

CREATE OR REPLACE TABLE _office_rules AS
SELECT rule_order, match_type, match_value, component, program_office_from_office
FROM _seed_award_component_rules
WHERE agency_code = getvariable('agency') AND match_column = 'awarding_office_name';

CREATE OR REPLACE TABLE _has_award_rules AS
SELECT count(*) > 0 AS has_rules FROM _seed_award_component_rules WHERE agency_code = getvariable('agency');

-- Agency names/abbreviation for reader text (from the snapshot's agency block).
CREATE OR REPLACE TABLE _agency_names AS
SELECT agency.agency_name AS agency_name, agency.abbreviation AS abbreviation
FROM read_json_auto('data/raw/*/reference/snapshot_info.json')
WHERE agency.toptier_code = getvariable('agency');
